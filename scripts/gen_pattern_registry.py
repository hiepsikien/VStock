"""Write the pattern registry the app can read from one generated module.

Run from the repo root:

    python scripts/gen_pattern_registry.py --write

`--check` compares the committed file with fresh output and exits non-zero on
a drift, so the pytest gate fails instead of letting the registry diverge from
`PROFILES`, `_FAMILY`, and `_PATTERN_TITLE`.

The source of truth stays in Python. This script reads it and writes
`src/sonify/patternRegistry.generated.ts`; the app reads the generated module.
Every row is one `(ensemble, pattern)` in `PROFILES`, plus the family-only ids
that have no wave profile. Each row carries `level` and `name_source` from
`PATTERN_META`, so a consumer can drop a texture without re-reading Python.
Rows are sorted and carry no timestamps, so two builds produce byte-identical
output.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))

from app.sonify.guitar_patterns import _FAMILY  # noqa: E402
from app.sonify.guitar_wave import PROFILES  # noqa: E402
from app.sonify.pattern_registry import PATTERN_META  # noqa: E402
from app.sonify.program import pattern_title  # noqa: E402

TS_PATH = ROOT / "src" / "sonify" / "patternRegistry.generated.ts"

HEADER = "// Generated by scripts/gen_pattern_registry.py. Do not edit.\n"

# `_PATTERN_TITLE` is keyed by id, not by ensemble, except for
# `thumb_cantabile`. A family-only id has no `PROFILES` row, so there is no
# owning ensemble to probe; probe the neutral one the docs already name.
FALLBACK_ENSEMBLE = "classic"


@dataclass(frozen=True)
class Row:
    """One registry row. `ensemble` is None for an id with no wave profile.

    `level` and `name_source` are copied verbatim from `PATTERN_META`; a
    texture's `name_source` is None even though its row may still carry the
    legacy title `_PATTERN_TITLE` holds.
    """

    ensemble: str | None
    pattern: str
    title: str
    family: str | None
    level: str
    name_source: str | None
    wave_profile: bool


def _title(pattern: str, ensemble: str | None) -> str:
    """Probe the owning ensemble, or the documented fallback when there is none."""
    if ensemble is not None:
        return pattern_title(pattern, ensemble)
    return pattern_title(pattern, FALLBACK_ENSEMBLE)


def build_rows() -> list[Row]:
    """The union of `PROFILES` and `_FAMILY`, in a stable order."""
    rows: list[Row] = []
    for ensemble, pattern in sorted(PROFILES):
        found = PATTERN_META[pattern]
        rows.append(
            Row(
                ensemble=ensemble,
                pattern=pattern,
                title=_title(pattern, ensemble),
                family=_FAMILY.get(pattern),
                level=found.level,
                name_source=found.name_source,
                wave_profile=True,
            )
        )

    profiled = {pattern for _ensemble, pattern in PROFILES}
    for pattern in sorted(set(_FAMILY) - profiled):
        # Family-only by definition: no `PROFILES` row, so no owning ensemble.
        # The title still probes, through the documented fallback.
        found = PATTERN_META[pattern]
        rows.append(
            Row(
                ensemble=None,
                pattern=pattern,
                title=_title(pattern, None),
                family=_FAMILY.get(pattern),
                level=found.level,
                name_source=found.name_source,
                wave_profile=False,
            )
        )

    return rows


def _row_payload(row: Row) -> dict[str, object]:
    return {
        "ensemble": row.ensemble,
        "pattern": row.pattern,
        "title": row.title,
        "family": row.family,
        "level": row.level,
        "nameSource": row.name_source,
        "waveProfile": row.wave_profile,
    }


def render_text() -> str:
    """The whole generated module, byte-stable for a stable registry."""
    body = json.dumps(
        [_row_payload(row) for row in build_rows()],
        ensure_ascii=False,
        indent=2,
    )
    return (
        HEADER
        + "export type PatternRegistryRow = {\n"
        + "  ensemble: string | null;\n"
        + "  pattern: string;\n"
        + "  title: string;\n"
        + "  family: string | null;\n"
        + "  level: 'topic' | 'texture';\n"
        + "  nameSource: string | null;\n"
        + "  waveProfile: boolean;\n"
        + "};\n\n"
        + "export const PATTERN_REGISTRY: readonly PatternRegistryRow[] = "
        + body
        + ";\n"
    )


def check(path: Path) -> bool:
    """True when `path` already holds fresh output."""
    return path.is_file() and path.read_text(encoding="utf-8") == render_text()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail on drift")
    parser.add_argument(
        "--write",
        action="store_true",
        help="write the generated file (the default when --check is absent)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=TS_PATH,
        help="output path; defaults to src/sonify/patternRegistry.generated.ts",
    )
    args = parser.parse_args(argv)

    text = render_text()
    path = args.out if args.out.is_absolute() else ROOT / args.out

    if args.check:
        if not check(path):
            print(f"out of date: {path}", file=sys.stderr)
            return 1
        return 0

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
