"""Write the one params schema the API and the app both read.

Run from the repo root:

    python scripts/gen_params_schema.py

`--check` compares the committed files with fresh output and exits non-zero on
a drift, so CI fails instead of letting the three copies diverge.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))

from app.sonify.params import SCHEMA_VERSION, schema_payload  # noqa: E402

JSON_PATH = BACKEND / "app" / "sonify" / "fixtures" / "params_schema.json"
TS_PATH = ROOT / "src" / "musicalize" / "paramsSchema.generated.ts"

HEADER = "// Generated by scripts/gen_params_schema.py. Do not edit.\n"


def _payload() -> dict:
    # The committed fixture is the schema itself, not the deployment switch.
    return schema_payload(enabled=True)


def _json_text(payload: dict) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=False) + "\n"


def _ts_text(payload: dict) -> str:
    body = json.dumps(payload, ensure_ascii=False, indent=2)
    return (
        HEADER
        + "export type ParamsFieldSchema = {\n"
        + "  key: string;\n"
        + "  label: string;\n"
        + '  type: "number";\n'
        + "  min: number;\n"
        + "  max: number;\n"
        + "  step: number;\n"
        + "  default: number;\n"
        + "  unit: string;\n"
        + "  description: string;\n"
        + "};\n\n"
        + "export type ParamsGroupSchema = {\n"
        + "  id: string;\n"
        + "  label: string;\n"
        + "  fields: ParamsFieldSchema[];\n"
        + "};\n\n"
        + "export type ParamsSchema = {\n"
        + "  schema: number;\n"
        + "  groups: ParamsGroupSchema[];\n"
        + "  defaultHash: string;\n"
        + "  baseBpm: Record<string, number | Record<string, number>>;\n"
        + "  enabled: boolean;\n"
        + "};\n\n"
        + f"export const PARAMS_SCHEMA: ParamsSchema = {body};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    payload = _payload()
    assert payload["schema"] == SCHEMA_VERSION
    outputs = {JSON_PATH: _json_text(payload), TS_PATH: _ts_text(payload)}

    if args.check:
        drifted = [
            path
            for path, text in outputs.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        for path in drifted:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if drifted else 0

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
